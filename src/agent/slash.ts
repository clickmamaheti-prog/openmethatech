// Slash commands adopted from Freebuff (Apache-2.0):
//   packages/agent-runtime/src/system-prompt/prompts.ts
//     (additionalSystemPrompts: /init, /export, /compact)
//   agents/base3.ts / base2 (slash behaviour)
//
// MethaTech versions, adapted to the local CLI:
// - /init reads the codebase and writes AGENTS.md (Freebuff writes
//   knowledge.md; MethaTech's convention file is AGENTS.md, which the
//   agent prompt already loads as a knowledge file).
// - /compact summarises the conversation through the model and
//   replaces the history with the summary.
// - /export writes a Markdown export to metatech-export-*.md in the
//   project folder (Freebuff: codebuff-export-*.md).

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import type { ChatMessage } from "../api.js";

export interface InitSummary {
  /** Markdown to write to AGENTS.md. */
  content: string;
  /** True when AGENTS.md already existed (caller should not overwrite silently). */
  existed: boolean;
}

/** Scan the project and draft an AGENTS.md (what it is, key code, commands). */
export function generateInitSummary(cwd: string): InitSummary {
  const existed = fs.existsSync(path.join(cwd, "AGENTS.md"));
  const pkg = readPackageJson(cwd);
  const files = listTopFiles(cwd);
  const scripts = pkg?.scripts ? Object.entries(pkg.scripts).map(([k, v]) => `- \`npm run ${k}\`: ${v}`).join("\n") : "";
  const lines: string[] = [
    `# AGENTS.md`,
    ``,
    `Project instructions for the MethaTech coding agent (auto-generated by \`/init\`; edit freely).`,
    ``,
    `## What this project is`,
    ``,
    pkg?.description ? pkg.description : `(describe the project in one or two sentences)`,
    ...(pkg?.name ? [`\nPackage: \`${pkg.name}\``] : []),
    ``,
    `## Key code`,
    ``,
    ...files.map((f) => `- \`${f}\``),
    ``,
    `## Commands`,
    ``,
    scripts.length > 0 ? scripts : `(no npm scripts found — list install/dev/test/build/lint commands here)`,
    ``,
    `## Conventions`,
    ``,
    `(conventions the agent must follow: style, what never to touch, how to verify changes)`,
    ``,
  ];
  return { content: lines.join("\n"), existed };
}

function readPackageJson(cwd: string): { name?: string; description?: string; scripts?: Record<string, string> } | null {
  try {
    return JSON.parse(fs.readFileSync(path.join(cwd, "package.json"), "utf-8")) as {
      name?: string;
      description?: string;
      scripts?: Record<string, string>;
    };
  } catch {
    return null;
  }
}

function listTopFiles(cwd: string): string[] {
  const out: string[] = [];
  const walk = (dir: string, depth: number) => {
    if (depth > 2 || out.length >= 40) return;
    let entries: fs.Dirent[];
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      if (out.length >= 40) return;
      if (["node_modules", ".git", "dist"].includes(e.name) || e.name.startsWith(".")) continue;
      const rel = path.relative(cwd, path.join(dir, e.name)).split(path.sep).join("/");
      if (e.isDirectory()) {
        out.push(`${rel}/`);
        walk(path.join(dir, e.name), depth + 1);
      } else if (e.isFile() && /\.(ts|tsx|js|jsx|py|go|rs|md|json)$/.test(e.name)) {
        out.push(rel);
      }
    }
  };
  walk(cwd, 0);
  return out;
}

/** Prompt used to summarise a conversation for /compact. */
export function compactPrompt(history: ChatMessage[]): string {
  const lines = history
    .filter((m) => m.role !== "system")
    .map((m) => `${m.role.toUpperCase()}: ${m.content.slice(0, 4000)}`)
    .join("\n\n");
  return (
    "Summarise the conversation below into a compact brief that lets a new session continue the same work without re-reading the full history. Keep: the user's goal, decisions made, files changed and their current state, open questions, and anything still to do. Drop: small talk, verbatim tool output, dead ends.\n\n" +
    lines
  );
}

export interface ExportOptions {
  cwd: string;
  model: string;
  mode: string;
  /** Display messages (role + content) to export. */
  messages: { role: string; content: string }[];
}

/** Write a Markdown export of the conversation; returns the file path. */
export function exportConversation(opts: ExportOptions): string {
  const stamp = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
  const fileName = `metatech-export-${stamp}.md`;
  const file = path.join(opts.cwd, fileName);
  const body = [
    `# MethaTech conversation export`,
    ``,
    `- Date: ${new Date().toISOString()}`,
    `- Model: ${opts.model}`,
    `- Mode: ${opts.mode}`,
    ``,
    ...opts.messages.map((m) => `## ${m.role}\n\n${m.content}\n`),
  ].join("\n");
  fs.writeFileSync(file, body, "utf-8");
  return file;
}

/** Short git summary for /init context (best effort, empty when not a repo). */
export function gitSummary(cwd: string): string {
  try {
    return execFileSync("git", ["status", "--short"], { cwd, timeout: 5000, encoding: "utf-8" }).trim().slice(0, 2000);
  } catch {
    return "";
  }
}
